// ===================== 辅助函数 =====================

/**
 * 安全的日志输出函数
 * 在插件代码中请使用此函数代替 console.log
 */
function pluginLog(message: string, data?: any) {
  const prefix = `[${pluginId}]`;
  if (data !== undefined) {
    console.log(prefix, message, data);
  } else {
    console.log(prefix, message);
  }
}

/**
 * 获取当前时间戳
 */
function now(): string {
  return new Date().toISOString();
}

